test('Cline emitter: createClineDelegationStrategy returns sequential strategy', () => {
    const strategy = createClineDelegationStrategy();

    assert.equal(strategy.type, 'sequential');
    assert.equal(typeof strategy.translate, 'function');

    const translated = strategy.translate({
        agentType: 'coder',
        promptTemplate: 'Build the feature',
    });

    assert.ok(
        translated.includes('coder'),
        'Translation should reference agent type'
    );
    assert.ok(
        translated.includes('memory bank'),
        'Translation should mention memory bank'
    );
    assert.ok(
        translated.includes('tasks.md'),
        'Translation should mention tasks.md checkbox tracking'
    );
});

