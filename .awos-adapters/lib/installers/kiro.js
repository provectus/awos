/** Kiro skills output directory relative to project root. */
const KIRO_SKILLS_DIR = '.kiro/skills';

/**
 * Protected directory prefixes relative to project root.
 * No overlay file writes are permitted under these paths.
 */
const PROTECTED_DIRS = ['.awos', 'commands', 'plugins', 'templates', 'src'];

/**
 * Check whether a target path falls under a protected directory.
 *
 * @param {string} projectRoot - Absolute path to the project root
 * @param {string} targetPath - Absolute or relative path to check
 * @returns {boolean} true if the path is under a protected directory
 */
function isProtectedPath(projectRoot, targetPath) {
    const resolvedRoot = path.resolve(projectRoot);
    const resolvedTarget = path.resolve(targetPath);

    for (const dir of PROTECTED_DIRS) {
        const protectedPrefix = resolvedRoot + path.sep + dir + path.sep;
        const protectedExact = resolvedRoot + path.sep + dir;
        if (resolvedTarget === protectedExact || resolvedTarget.startsWith(protectedPrefix)) {
            return true;
        }
    }
    return false;
}

/** Kiro MCP configuration file path relative to project root. */
const KIRO_MCP_PATH = '.kiro/settings/mcp.json';

/**
 * @typedef {Object} OverlayInstallResult
 * @property {string[]} skills - Skill names installed
 * @property {string[]} agents - Agent names installed
 * @property {string[]} mcps - MCP server names installed
 * @property {string[]} warnings - Non-fatal issues
 * @property {string[]} errors - Fatal issues per resource
 */

/**
 * Extract YAML frontmatter from a markdown file content.
 * Looks for content between opening `---\n` and closing `\n---\n` (or `\n---` at EOF).
 *
 * @param {string} content - File content
 * @returns {string|null} Raw frontmatter string or null if not found
 */
function extractFrontmatter(content) {
    if (!content.startsWith('---\n') && !content.startsWith('---\r\n')) {
        return null;
    }
    const endMarker = content.indexOf('\n---\n', 4);
    const endMarkerEof = content.indexOf('\n---', 4);
    if (endMarker !== -1) {
        return content.slice(4, endMarker);
    }
    // Handle case where --- is at end of file without trailing newline
    if (endMarkerEof !== -1 && (endMarkerEof + 4 === content.length || content.slice(endMarkerEof + 4).trim() === '')) {
        return content.slice(4, endMarkerEof);
    }
    return null;
}

/**
 * Extract a field value from raw YAML frontmatter content.
 * Simple line-based extraction — no full YAML parser needed.
 *
 * @param {string} frontmatter - Raw frontmatter string
 * @param {string} field - Field name to extract
 * @returns {string|null} Field value or null if not found
 */
function extractFrontmatterField(frontmatter, field) {
    const lines = frontmatter.split('\n');
    for (const line of lines) {
        const match = line.match(new RegExp(`^${field}:\\s*(.+)$`));
        if (match) {
            return match[1].trim().replace(/^['"]|['"]$/g, '');
        }
    }
    return null;
}

/**
 * Install overlay resources into .kiro/ structure.
 *
 * Currently implements skill installation. Agent and MCP installation
 * will be added in subsequent tasks.
 *
 * @param {string} projectRoot
 * @param {Array<{name: string, type: string, absolutePath: string, description?: string, tags?: string[], source?: string}>} resources - Pre-validated overlay resources
 * @param {Object} [options]
 * @param {boolean} [options.dryRun=false]
 * @returns {Promise<OverlayInstallResult>}
 */
async function installOverlay(projectRoot, resources, options = {}) {
    const { dryRun = false } = options;

    /** @type {OverlayInstallResult} */
    const result = {
        skills: [],
        agents: [],
        mcps: [],
        warnings: [],
        errors: [],
    };

    // --- Skill Installation ---
    const skillResources = resources.filter((r) => r.type === 'skill');

    for (const resource of skillResources) {
        try {
            const content = await fsp.readFile(resource.absolutePath, 'utf8');
            const frontmatter = extractFrontmatter(content);

            if (!frontmatter) {
                result.warnings.push(
                    `Skill "${resource.name}": missing YAML frontmatter in ${resource.absolutePath}`
                );
                continue;
            }

            const skillName = extractFrontmatterField(frontmatter, 'name');

            if (!skillName) {
                result.warnings.push(
                    `Skill "${resource.name}": missing "name" field in frontmatter of ${resource.absolutePath}`
                );
                continue;
            }

            const targetDir = path.join(projectRoot, KIRO_SKILLS_DIR, skillName);
            const sourceFilename = path.basename(resource.absolutePath);
            const targetPath = path.join(targetDir, sourceFilename);

            if (isProtectedPath(projectRoot, targetPath)) {
                result.errors.push(
                    `Skill "${resource.name}": target path "${targetPath}" is under a protected directory`
                );
                continue;
            }

            if (!dryRun) {
                await fsp.mkdir(targetDir, { recursive: true });
                await fsp.copyFile(resource.absolutePath, targetPath);
            }

            result.skills.push(skillName);
        } catch (err) {
            result.errors.push(
                `Skill "${resource.name}": ${err.message}`
            );
        }
    }

    // --- Agent Installation ---
    const agentResources = resources.filter((r) => r.type === 'agent');
    const overlaySkillNames = new Set(
        resources.filter((r) => r.type === 'skill').map((r) => r.name)
    );

    for (const resource of agentResources) {
        try {
            const content = await fsp.readFile(resource.absolutePath, 'utf8');
            const frontmatter = extractFrontmatter(content);

            if (!frontmatter) {
                result.warnings.push(
                    `Agent "${resource.name}": missing YAML frontmatter in ${resource.absolutePath}`
                );
                continue;
            }

            const agentName = extractFrontmatterField(frontmatter, 'name');
            const description = extractFrontmatterField(frontmatter, 'description') || '';
            const skillsRaw = extractFrontmatterField(frontmatter, 'skills') || '';

            if (!agentName) {
                result.warnings.push(
                    `Agent "${resource.name}": missing "name" field in frontmatter of ${resource.absolutePath}`
                );
                continue;
            }

            // Parse skills as comma-separated list
            const skillsList = skillsRaw
                .split(',')
                .map((s) => s.trim())
                .filter((s) => s.length > 0);

            // Verify each skill exists in overlay resources or on disk
            const missingSkills = [];
            for (const skillName of skillsList) {
                const inOverlay = overlaySkillNames.has(skillName);
                if (!inOverlay) {
                    const skillDir = path.join(projectRoot, KIRO_SKILLS_DIR, skillName);
                    if (!fs.existsSync(skillDir)) {
                        missingSkills.push(skillName);
                    }
                }
            }

            if (missingSkills.length > 0) {
                result.warnings.push(
                    `Agent "${agentName}": missing skill dependencies: ${missingSkills.join(', ')}. Skipping agent.`
                );
                continue;
            }

            // Generate steering file
            const steeringDir = path.join(projectRoot, KIRO_STEERING_DIR);
            const steeringPath = path.join(steeringDir, `${agentName}.md`);

            if (isProtectedPath(projectRoot, steeringPath)) {
                result.errors.push(
                    `Agent "${resource.name}": target path "${steeringPath}" is under a protected directory`
                );
                continue;
            }

            const skillsSection = skillsList.map((s) => `- ${s}`).join('\n');
            const steeringContent =
                `---\ninclusion: manual\n---\n\n# ${agentName}\n\n` +
                `> ${description}\n\n` +
                `## Skills\n\n${skillsSection}\n\n` +
                `## Instructions\n\n` +
                `This agent specializes in ${description}.\n` +
                `Activate with \`#${agentName}\` in chat.\n`;

            if (!dryRun) {
                await fsp.mkdir(steeringDir, { recursive: true });
                await fsp.writeFile(steeringPath, steeringContent, 'utf8');
            }

            result.agents.push(agentName);
        } catch (err) {
            result.errors.push(
                `Agent "${resource.name}": ${err.message}`
            );
        }
    }

    // --- MCP Installation ---
    const mcpResources = resources.filter((r) => r.type === 'mcp');

    if (mcpResources.length > 0) {
        const mcpFilePath = path.join(projectRoot, KIRO_MCP_PATH);

        // Read existing mcp.json or start fresh
        let mcpConfig = { mcpServers: {} };
        try {
            const existingContent = await fsp.readFile(mcpFilePath, 'utf8');
            const parsed = JSON.parse(existingContent);
            if (parsed && typeof parsed === 'object') {
                mcpConfig = parsed;
                if (!mcpConfig.mcpServers || typeof mcpConfig.mcpServers !== 'object') {
                    mcpConfig.mcpServers = {};
                }
            }
        } catch (err) {
            if (err.code === 'ENOENT') {
                // File doesn't exist — start with empty config
            } else if (err instanceof SyntaxError) {
                result.warnings.push(
                    `MCP: existing ${KIRO_MCP_PATH} has invalid JSON, starting fresh`
                );
            } else {
                result.warnings.push(
                    `MCP: could not read ${KIRO_MCP_PATH}: ${err.message}, starting fresh`
                );
            }
            mcpConfig = { mcpServers: {} };
        }

        let mcpModified = false;

        for (const resource of mcpResources) {
            try {
                const content = await fsp.readFile(resource.absolutePath, 'utf8');

                let serverEntries;
                try {
                    serverEntries = JSON.parse(content);
                } catch (parseErr) {
                    result.warnings.push(
                        `MCP "${resource.name}": invalid JSON in ${resource.absolutePath}`
                    );
                    continue;
                }

                if (!serverEntries || typeof serverEntries !== 'object' || Array.isArray(serverEntries)) {
                    result.warnings.push(
                        `MCP "${resource.name}": expected a JSON object with server entries in ${resource.absolutePath}`
                    );
                    continue;
                }

                for (const serverName of Object.keys(serverEntries)) {
                    if (mcpConfig.mcpServers[serverName]) {
                        result.warnings.push(
                            `MCP "${resource.name}": server "${serverName}" already exists in ${KIRO_MCP_PATH}, skipping`
                        );
                        continue;
                    }

                    mcpConfig.mcpServers[serverName] = serverEntries[serverName];
                    result.mcps.push(serverName);
                    mcpModified = true;
                }
            } catch (err) {
                result.errors.push(
                    `MCP "${resource.name}": ${err.message}`
                );
            }
        }

        if (mcpModified && !dryRun) {
            if (isProtectedPath(projectRoot, mcpFilePath)) {
                result.errors.push(
                    `MCP: target path "${mcpFilePath}" is under a protected directory`
                );
            } else {
                const mcpDir = path.dirname(mcpFilePath);
                await fsp.mkdir(mcpDir, { recursive: true });
                await fsp.writeFile(mcpFilePath, JSON.stringify(mcpConfig, null, 2), 'utf8');
            }
        }
    }

    return result;
}

