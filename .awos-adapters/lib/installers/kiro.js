'use strict';

/**
 * Kiro Installer for the multi-IDE adapter layer.
 *
 * Transforms generated adapter files from `.awos-adapters/kiro/` into
 * Kiro-native format and installs them into the project's `.kiro/`
 * directory:
 *   - Steering files  → `.kiro/steering/` (with `inclusion: manual` frontmatter)
 *   - Hook markdown   → `.kiro/hooks/` (converted to JSON hook schema)
 *
 * This completes the "last mile" that generate.js does not handle.
 *
 * @module lib/installers/kiro
 */

const fs = require('node:fs');
const fsp = require('node:fs/promises');
const path = require('node:path');

// ---------------------------------------------------------------------
// Constants
// ---------------------------------------------------------------------

/** Kiro steering output directory relative to project root. */
const KIRO_STEERING_DIR = '.kiro/steering';

/** Kiro hooks output directory relative to project root. */
const KIRO_HOOKS_DIR = '.kiro/hooks';

/** Frontmatter prepended to all installed steering files. */
const STEERING_FRONTMATTER = `---\ninclusion: manual\n---\n`;

/** Hook JSON schema version. */
const HOOK_VERSION = '1.0.0';

// ---------------------------------------------------------------------
// Steering Installation
// ---------------------------------------------------------------------

/**
 * Install steering files from the generated adapter directory into
 * `.kiro/steering/`. Adds `inclusion: manual` frontmatter so Kiro
 * exposes them via `#name` in chat.
 *
 * @param {string} projectRoot - Absolute path to the project root
 * @param {Object} [options]
 * @param {boolean} [options.dryRun=false] - If true, returns files without writing
 * @returns {Promise<{installed: string[], skipped: string[], errors: string[]}>}
 */
async function installSteering(projectRoot, options = {}) {
    const { dryRun = false } = options;
    const sourceDir = path.join(projectRoot, '.awos-adapters', 'kiro', 'steering');
    const targetDir = path.join(projectRoot, KIRO_STEERING_DIR);
    const installed = [];
    const skipped = [];
    const errors = [];

    if (!fs.existsSync(sourceDir)) {
        errors.push(`Source directory not found: ${sourceDir}`);
        return { installed, skipped, errors };
    }

    if (!dryRun) {
        await fsp.mkdir(targetDir, { recursive: true });
    }

    const entries = await fsp.readdir(sourceDir);
    const mdFiles = entries.filter((f) => f.endsWith('.md'));

    for (const file of mdFiles) {
        const sourcePath = path.join(sourceDir, file);
        const targetPath = path.join(targetDir, file);

        try {
            let content = await fsp.readFile(sourcePath, 'utf8');

            // Strip the auto-generated HTML comment header if present
            content = content.replace(
                /^<!-- Auto-generated by generate-adapters — do not edit manually -->\s*\n*/,
                ''
            );

            // Replace /awos: command references with # references for Kiro
            content = content.replace(/`\/awos:(\w+)`/g, '`#$1`');
            content = content.replace(/\/awos:(\w+)/g, '#$1');

            // Prepend the Kiro steering frontmatter
            const finalContent = STEERING_FRONTMATTER + content;

            if (!dryRun) {
                await fsp.writeFile(targetPath, finalContent, 'utf8');
            }

            installed.push(file);
        } catch (err) {
            errors.push(`Failed to install ${file}: ${err.message}`);
        }
    }

    return { installed, skipped, errors };
}

