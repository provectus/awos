const { discover } = require('../resource-resolver');

/**
 * Run the complete Kiro installation: steering + hooks + overlay.
 *
 * The overlay phase runs after steering and hooks. It discovers company
 * overlay resources from `.awos-company/manifest.json` and installs them
 * into `.kiro/`. If no overlay exists, the overlay result is empty and
 * no filesystem operations occur.
 *
 * @param {string} projectRoot - Absolute path to the project root
 * @param {Object} [options]
 * @param {boolean} [options.dryRun=false] - If true, returns results without writing
 * @returns {Promise<{steering: Object, hooks: Object, overlay: OverlayInstallResult}>}
 */
async function install(projectRoot, options = {}) {
    const steeringResult = await installSteering(projectRoot, options);
    const hooksResult = await installHooks(projectRoot, options);

    // Overlay phase — runs after standard installation
    let overlayResult = { skills: [], agents: [], mcps: [], warnings: [], errors: [] };
    const discoveryResult = discover(projectRoot);

    if (discoveryResult.resources.length > 0 && discoveryResult.errors.length === 0) {
        overlayResult = await installOverlay(projectRoot, discoveryResult.resources, options);
        // Include discovery warnings in overlay result
        overlayResult.warnings = [...discoveryResult.warnings, ...overlayResult.warnings];
    } else if (discoveryResult.errors.length > 0) {
        overlayResult.errors = discoveryResult.errors;
        overlayResult.warnings = discoveryResult.warnings;
    }

    return {
        steering: steeringResult,
        hooks: hooksResult,
        overlay: overlayResult,
    };
}

