/**
 * Install hooks from generated adapter directory into `.kiro/hooks/`.
 * Creates a `userTriggered` JSON hook for each AWOS command that has
 * a steering file, plus `postTaskExecution` hooks for commands that
 * have delegation (implement, tasks, tech, hire).
 *
 * @param {string} projectRoot - Absolute path to the project root
 * @param {Object} [options]
 * @param {boolean} [options.dryRun=false] - If true, returns files without writing
 * @returns {Promise<{installed: string[], errors: string[]}>}
 */
async function installHooks(projectRoot, options = {}) {
    const { dryRun = false } = options;
    const steeringSource = path.join(projectRoot, '.awos-adapters', 'kiro', 'steering');
    const hookSource = path.join(projectRoot, '.awos-adapters', 'kiro', 'hooks');
    const targetDir = path.join(projectRoot, KIRO_HOOKS_DIR);
    const installed = [];
    const errors = [];

    if (!dryRun) {
        await fsp.mkdir(targetDir, { recursive: true });
    }

    // 1. Create userTriggered hooks for each steering file
    if (fs.existsSync(steeringSource)) {
        const entries = await fsp.readdir(steeringSource);
        const mdFiles = entries.filter((f) => f.endsWith('.md'));

        for (const file of mdFiles) {
            const commandName = path.basename(file, '.md');
            const hookConfig = HOOK_PROMPTS[commandName];

            if (!hookConfig) continue;

            const hook = {
                name: `AWOS: ${capitalize(commandName)}`,
                version: HOOK_VERSION,
                description: hookConfig.description,
                when: {
                    type: 'userTriggered',
                },
                then: {
                    type: 'askAgent',
                    prompt: hookConfig.prompt,
                },
            };

            const hookFileName = `awos-${commandName}.json`;
            const targetPath = path.join(targetDir, hookFileName);

            try {
                if (!dryRun) {
                    await fsp.writeFile(
                        targetPath,
                        JSON.stringify(hook, null, 2) + '\n',
                        'utf8'
                    );
                }
                installed.push(hookFileName);
            } catch (err) {
                errors.push(`Failed to install hook ${hookFileName}: ${err.message}`);
            }
        }
    }

    // 2. Create postTaskExecution hooks from hook markdown files
    if (fs.existsSync(hookSource)) {
        const entries = await fsp.readdir(hookSource);
        const hookMdFiles = entries.filter((f) => f.endsWith('.md'));

        for (const file of hookMdFiles) {
            const baseName = path.basename(file, '.md');
            // e.g. "implement-post-task" → command "implement"
            const commandName = baseName.replace(/-post-task$/, '');

            const hook = {
                name: `AWOS: Post-Task — ${capitalize(commandName)}`,
                version: HOOK_VERSION,
                description:
                    `After all tasks complete for ${commandName}: announce status ` +
                    'and suggest running verify.',
                when: {
                    type: 'postTaskExecution',
                },
                then: {
                    type: 'askAgent',
                    prompt:
                        `All tasks have been marked complete. ` +
                        `Announce the completion status with task count and percentage. ` +
                        `Suggest running the #verify workflow to validate acceptance criteria.`,
                },
            };

            const hookFileName = `awos-${baseName}.json`;
            const targetPath = path.join(targetDir, hookFileName);

            try {
                if (!dryRun) {
                    await fsp.writeFile(
                        targetPath,
                        JSON.stringify(hook, null, 2) + '\n',
                        'utf8'
                    );
                }
                installed.push(hookFileName);
            } catch (err) {
                errors.push(`Failed to install hook ${hookFileName}: ${err.message}`);
            }
        }
    }

    return { installed, errors };
}

