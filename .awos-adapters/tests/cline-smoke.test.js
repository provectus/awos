test('Cline emitter: works with minimal IR (no delegations)', () => {
    const ir = createCommandIR('spec');
    ir.role.title = 'Spec Writer';
    ir.role.description = 'Creates specifications.';
    ir.task.goal = 'Write a spec.';
    ir.process.steps = [
        {
            stepNumber: 1,
            title: 'Gather Requirements',
            body: 'Read existing docs.',
            toolReferences: [],
            delegations: [],
        },
    ];

    const result = emit(ir);

    assert.ok(result.files.length >= 2, 'Should still produce rule + memory bank');
    const ruleFile = result.files.find((f) =>
        f.relativePath.startsWith('rules/')
    );
    assert.ok(
        !ruleFile.content.includes('Task Completion Tracking'),
        'Should NOT include task completion when no delegations'
    );
});
