'use strict';

const { test } = require('node:test');
const assert = require('node:assert/strict');

const { emit, createClineDelegationStrategy } = require('../lib/emitters/cline.js');
const { createCommandIR } = require('../lib/ir.js');

/**
 * Build a realistic sample IR for the implement command.
 */
function buildSampleIR() {
    const ir = createCommandIR('implement');
    ir.frontmatter.description =
        'Runs tasks — delegates coding to sub-agents, tracks progress.';
    ir.role.title = 'Lead Implementation Agent';
    ir.role.description =
        'You are a Lead Implementation Agent responsible for executing tasks.';
    ir.role.rules = ['Always track progress', 'Delegate appropriately'];
    ir.task.goal = 'Execute the pending work for a given specification.';
    ir.io.contextFiles = [
        'context/spec/[index]-[name]/functional-spec.md',
        'context/spec/[index]-[name]/tasks.md',
    ];
    ir.io.outputs = [
        { name: 'tasks.md', description: 'Updated with completed checkboxes' },
    ];
    ir.interaction.tools = ['AskUserQuestion'];
    ir.interaction.notes = 'Use AskUserQuestion for multiple-choice questions';
    ir.process.steps = [
        {
            stepNumber: 1,
            title: 'Load Context',
            body: 'Read the tasks.md file.',
            toolReferences: [
                {
                    tool: 'Read',
                    context: 'Read tasks.md',
                    lineNumber: 10,
                    parameters: { _positional: 'context/spec/test/tasks.md' },
                },
            ],
            delegations: [],
        },
        {
            stepNumber: 2,
            title: 'Delegate Implementation',
            body: 'Delegate the next task to a sub-agent.',
            toolReferences: [
                {
                    tool: 'Agent',
                    context: 'Agent(subagent_type=coder)',
                    lineNumber: 30,
                    parameters: { subagent_type: 'coder' },
                },
            ],
            delegations: [
                {
                    agentType: 'coder',
                    promptTemplate: 'Implement the feature as specified.',
                },
            ],
        },
    ];
    ir.toolReferences = [
        { tool: 'Read', context: 'Read tasks.md', lineNumber: 10, parameters: {} },
        { tool: 'Agent', context: 'Agent()', lineNumber: 30, parameters: {} },
        {
            tool: 'AskUserQuestion',
            context: 'AskUserQuestion',
            lineNumber: 5,
            parameters: {},
        },
    ];
    return ir;
}

test('Cline emitter: module loads and exports emit + createClineDelegationStrategy', () => {
    assert.equal(typeof emit, 'function');
    assert.equal(typeof createClineDelegationStrategy, 'function');
});

test('Cline emitter: emit() produces rule file and memory bank template', () => {
    const ir = buildSampleIR();
    const result = emit(ir);

    assert.ok(result.files.length >= 2, 'Should produce at least 2 files');

    const ruleFile = result.files.find((f) =>
        f.relativePath.startsWith('rules/')
    );
    assert.ok(ruleFile, 'Should produce a rule file');
    assert.equal(ruleFile.relativePath, 'rules/implement.md');

    const memFile = result.files.find((f) =>
        f.relativePath.startsWith('memory-bank/')
    );
    assert.ok(memFile, 'Should produce a memory bank template');
    assert.equal(memFile.relativePath, 'memory-bank/implement-state.md');
});

